import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

/// Stages the version-1 dep-push receipt without replacing the previous receipt.
///
/// Prepare only after checkout validation, commit after the pubspec save, and
/// always dispose the plan. A failed validation/save never refreshes the receipt.
class PushReceiptRepository {
  /// Creates the filesystem receipt adapter.
  const PushReceiptRepository();

  /// Checks the destination and stages a flushed sibling file for atomic rename.
  PushReceiptPlan prepare(Directory consumer,
      {required DateTime completedAt, required String toolVersion}) {
    final file = File(p.join(consumer.path, 'dep-sync.lock'));
    final type = FileSystemEntity.typeSync(file.path, followLinks: false);
    if (type != FileSystemEntityType.file &&
        type != FileSystemEntityType.notFound) {
      throw StateError(
          'dep-sync.lock must be a regular file, not a symlink or directory.');
    }
    final original = file.existsSync() ? file.readAsStringSync() : null;
    final utc = completedAt
        .toUtc()
        .toIso8601String()
        .replaceFirst(RegExp(r'\.\d+Z$'), 'Z');
    final content = '# Generated by dep-push. Do not edit manually.\n\n'
        'lock_version: 1\n\nlast_dep_push:\n'
        '  completed_at_utc: ${jsonEncode(utc)}\n'
        '  tool_version: ${jsonEncode(toolVersion)}\n';
    final temporary = consumer.createTempSync('.dep-sync-receipt-');
    try {
      final staged = File(p.join(temporary.path, 'dep-sync.lock'));
      if (original != null) file.copySync(staged.path);
      staged.writeAsStringSync(content, flush: true);
      return PushReceiptPlan._(file, staged, temporary, original);
    } catch (_) {
      temporary.deleteSync(recursive: true);
      rethrow;
    }
  }
}

/// Owns a prepared receipt and its temporary directory until committed/disposed.
class PushReceiptPlan {
  PushReceiptPlan._(this._file, this._staged, this._temporary, this._original);
  final File _file;
  final File _staged;
  final Directory _temporary;
  final String? _original;

  /// Atomically refreshes the receipt, rejecting concurrent changes or symlinks.
  void commit() {
    final type = FileSystemEntity.typeSync(_file.path, followLinks: false);
    if (type != FileSystemEntityType.file &&
        type != FileSystemEntityType.notFound) {
      throw StateError(
          'dep-sync.lock changed during synchronization. Rerun dep-push.');
    }
    final current = _file.existsSync() ? _file.readAsStringSync() : null;
    if (current != _original) {
      throw StateError(
          'dep-sync.lock changed during synchronization. Rerun dep-push.');
    }
    _staged.renameSync(_file.path);
  }

  /// Removes staging files after success or failure, leaving the receipt alone.
  void dispose() {
    if (_temporary.existsSync()) _temporary.deleteSync(recursive: true);
  }
}
